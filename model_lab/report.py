from collections import defaultdict
from html import escape


def percentile(values, fraction):
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, round((len(ordered) - 1) * fraction))] if ordered else 0


def build_report(rows) -> str:
    grouped = defaultdict(list)
    for row in rows: grouped[row[1]].append(row)
    cards = []
    for model, items in sorted(grouped.items()):
        quality = sum(row[4] for row in items) / len(items)
        reliability = sum(row[6] is None for row in items) / len(items)
        latencies = [row[5] for row in items]
        failures = "".join(f"<li><b>{escape(r[2])}</b>: {escape(r[6] or 'score '+str(round(r[4],3)))}</li>"
                           for r in items if r[6] or r[4] < 1)
        cards.append(f"""<section><h2>{escape(model)}</h2><div class=metrics>
        <strong>{quality*reliability:.1%}<small> composite</small></strong>
        <span>{quality:.1%}<small> quality</small></span><span>{reliability:.1%}<small> reliability</small></span>
        <span>{percentile(latencies,.5):.0f}ms<small> median</small></span><span>{percentile(latencies,.95):.0f}ms<small> p95</small></span>
        </div><details><summary>Failures and partial scores</summary><ul>{failures or '<li>None</li>'}</ul></details></section>""")
    return f"""<!doctype html><meta charset=utf-8><meta name=viewport content='width=device-width'>
    <title>Ollama Evaluation Lab</title><style>
    body{{font:16px system-ui;max-width:1000px;margin:40px auto;padding:0 20px;background:#0b1020;color:#e8edf7}}
    h1{{font-size:42px}}section{{background:#151d33;border:1px solid #2b385b;border-radius:16px;padding:22px;margin:18px 0}}
    .metrics{{display:grid;grid-template-columns:repeat(auto-fit,minmax(120px,1fr));gap:14px}}
    strong,span{{font-size:25px}}small{{display:block;color:#9caccc;font-size:12px;text-transform:uppercase}}
    summary{{cursor:pointer;margin-top:20px}}code{{color:#7ee787}}</style>
    <h1>Local Model Leaderboard</h1><p>Auditable benchmark results generated by Ollama Evaluation Lab.</p>{''.join(cards)}"""
